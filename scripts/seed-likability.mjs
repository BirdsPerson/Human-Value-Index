// Seeds the People judge for public figures from YouGov US ratings in
// docs/methodology/benchmarks.json -> src/peopleData.js (generated; do not hand-edit),
// and writes docs/methodology/cube-points.json (machine + people point per figure).
// Rerun after scripts/fetch_benchmarks.py:  node scripts/seed-likability.mjs
import fs from "node:fs";
import { likabilityFrom, judged } from "../src/cube.js";

const bench = JSON.parse(fs.readFileSync(new URL("../docs/methodology/benchmarks.json", import.meta.url)));
const asOf = String(bench.generated || "").slice(0, 10);
const people = {};
for (const [name, rec] of Object.entries(bench.figures || {})) {
  const yg = rec?.yougov_us;
  const likability = likabilityFrom(yg);
  if (likability == null) continue;
  people[name] = { likability, source: "YouGov US ratings", fame: yg.fame_pct, liked: yg.popularity_pct, disliked: yg.disliked_pct, asOf, url: yg.url || null };
}
fs.writeFileSync(new URL("../src/peopleData.js", import.meta.url),
  `// GENERATED by scripts/seed-likability.mjs from docs/methodology/benchmarks.json. Do not hand-edit.\n` +
  `// The People judge for public figures: likability from YouGov US ratings (see src/cube.js likabilityFrom).\n` +
  `export const PEOPLE = ${JSON.stringify(people, null, 1)};\n`);

const { FAMOUS_FIGURES } = await import(`../src/figures.js?${Date.now()}`);
const points = FAMOUS_FIGURES.map(f => {
  const j = judged({ warmth: f.warmth, competence: f.competence, quadrant: f.quadrant }, f.people);
  return { name: f.name, score: f.score, machine: { warmth: f.warmth, competence: f.competence, quadrant: f.quadrant },
    people: j.people ? { likability: j.people.likability, competence: f.competence, quadrant: j.people.quadrant, gap: j.people.gap } : null, judge: j.judge };
});
fs.writeFileSync(new URL("../docs/methodology/cube-points.json", import.meta.url), JSON.stringify({ generated: new Date().toISOString(), note: "machine = warmth (conduct) x competence; people = likability (YouGov US) x machine competence", points }, null, 1));
console.log(`people data: ${Object.keys(people).length} figures; cube points: ${points.length}; with people: ${points.filter(p => p.people).length}`);
